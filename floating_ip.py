"""Managed VRRP floating IPs, independent of systemd-networkd address files.

The VIP is installed ONLY by keepalived on the elected MASTER. Do not put it
in a .network file or assign it with ip addr on both cluster nodes.
"""
import ipaddress
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

CONFIG = Path('/var/lib/router-manager/config.json')
KEEPALIVED = Path('/etc/keepalived/router-manager-vrrp.conf')
SERVICE = 'router-manager-vrrp.service'


def validate(entries, interfaces=None):
    if not isinstance(entries, list) or len(entries) > 64:
        raise ValueError('floating_ips must be a list with at most 64 entries')
    ids, vips = set(), set()
    output = []
    for item in entries:
        if not isinstance(item, dict):
            raise ValueError('Invalid floating IP entry')
        interface = item.get('interface', '')
        if not isinstance(interface, str) or not re.fullmatch(r'[a-zA-Z0-9_.:-]{1,15}', interface) or interface == 'lo':
            raise ValueError('Invalid interface')
        if interfaces is not None and interface not in interfaces:
            raise ValueError(f'Interface does not exist: {interface}')
        vip = str(ipaddress.ip_interface(item['address']))
        if ipaddress.ip_interface(vip).ip.is_multicast or ipaddress.ip_interface(vip).ip.is_unspecified:
            raise ValueError('Floating IP must be a unicast address')
        vrid = int(item['vrid'])
        priority = int(item.get('priority', 100))
        advert = int(item.get('advert_int', 1))
        if not 1 <= vrid <= 255 or not 1 <= priority <= 254 or not 1 <= advert <= 30:
            raise ValueError('VRID, priority or advertisement interval out of range')
        key = (interface, vrid)
        if key in ids or (interface, vip) in vips:
            raise ValueError('Duplicate interface/VRID or floating IP')
        ids.add(key)
        vips.add((interface, vip))
        peers = item.get('peers', [])
        if not isinstance(peers, list) or len(peers) > 16:
            raise ValueError('Invalid VRRP peers')
        family = ipaddress.ip_interface(vip).version
        peers = [str(ipaddress.ip_address(p)) for p in peers]
        if any(ipaddress.ip_address(p).version != family for p in peers):
            raise ValueError('VRRP peers must use the floating IP address family')
        source = item.get('source_address', '')
        source = str(ipaddress.ip_address(source)) if source else ''
        if source and ipaddress.ip_address(source).version != family:
            raise ValueError('VRRP source address family mismatch')
        if peers and not source:
            raise ValueError('Unicast VRRP requires a local source address')
        output.append({'interface': interface, 'address': vip, 'vrid': vrid,
                       'priority': priority, 'advert_int': advert,
                       'peers': peers, 'source_address': source,
                       'preempt': bool(item.get('preempt', False))})
    return output


def render(entries):
    lines = ['# Generated by Router Manager. Do not edit manually.',
             'global_defs {', '    enable_script_security', '}']
    for idx, item in enumerate(entries):
        family = ipaddress.ip_interface(item['address']).version
        lines += ['', f'vrrp_instance RM_VIP_{idx + 1} {{',
                  '    state BACKUP', f'    interface {item["interface"]}',
                  f'    virtual_router_id {item["vrid"]}',
                  f'    priority {item["priority"]}',
                  f'    advert_int {item["advert_int"]}',
                  f'    {"nopreempt" if not item["preempt"] else "preempt"}',
                  f'    native_ipv6' if family == 6 else '    # IPv4 VRRP']
        if item['peers']:
            lines += [f'    unicast_src_ip {item["source_address"]}', '    unicast_peer {']
            lines += [f'        {peer}' for peer in item['peers']]
            lines += ['    }']
        lines += ['    virtual_ipaddress {', f'        {item["address"]} dev {item["interface"]}',
                  '    }', '}']
    return '\n'.join(lines) + '\n'


def atomic_write(path, content, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix='.router-manager-', dir=str(path.parent))
    try:
        with os.fdopen(fd, 'w') as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def read():
    if not CONFIG.exists():
        return []
    root = json.loads(CONFIG.read_text())
    return validate(root.get('floating_ips', []))


def status(entries):
    try:
        raw = subprocess.run(['ip', '-j', 'address', 'show'], capture_output=True,
                             text=True, timeout=5, check=True)
        present = {(link['ifname'], a['local']) for link in json.loads(raw.stdout)
                   for a in link.get('addr_info', [])}
    except (OSError, ValueError, subprocess.SubprocessError):
        present = set()
    return [{**e, 'owned_here': (e['interface'], str(ipaddress.ip_interface(e['address']).ip)) in present}
            for e in entries]


def install(entries):
    """Validate before writing, then commit config and managed daemon config.

    No changes to systemd-networkd. An empty list stops the managed VRRP unit.
    """
    if not shutil.which('keepalived'):
        raise RuntimeError('Install keepalived before configuring floating IPs')
    if not Path('/etc/systemd/system/router-manager-vrrp.service').exists():
        raise RuntimeError('Install router-manager-vrrp.service first')
    interfaces = {p.name for p in Path('/sys/class/net').iterdir()}
    entries = validate(entries, interfaces)
    generated = render(entries)
    # Validate generated configuration before replacing live config.
    with tempfile.NamedTemporaryFile(mode='w', prefix='rm-vrrp-', suffix='.conf', delete=False) as f:
        f.write(generated)
        test_path = f.name
    try:
        result = subprocess.run(['keepalived', '-t', '-f', test_path], capture_output=True,
                                text=True, timeout=15)
        if result.returncode:
            raise RuntimeError('keepalived validation failed: ' + (result.stderr or result.stdout)[-1200:])
    finally:
        os.unlink(test_path)
    old_cfg = KEEPALIVED.read_text() if KEEPALIVED.exists() else None
    root = json.loads(CONFIG.read_text()) if CONFIG.exists() else {'version': 1, 'files': {}, 'routes': []}
    old_json = CONFIG.read_text() if CONFIG.exists() else None
    root['floating_ips'] = entries
    try:
        atomic_write(KEEPALIVED, generated, 0o600)
        action = 'restart' if entries else 'stop'
        result = subprocess.run(['systemctl', action, SERVICE], capture_output=True,
                                text=True, timeout=25)
        if result.returncode:
            raise RuntimeError('VRRP service ' + action + ' failed: ' + result.stderr[-1200:])
        atomic_write(CONFIG, json.dumps(root, indent=2) + '\n')
        subprocess.run(['systemctl', 'enable' if entries else 'disable', SERVICE],
                       capture_output=True, timeout=15, check=False)
    except Exception:
        if old_cfg is not None:
            atomic_write(KEEPALIVED, old_cfg)
        else:
            KEEPALIVED.unlink(missing_ok=True)
        if old_json is not None:
            atomic_write(CONFIG, old_json)
        subprocess.run(['systemctl', 'restart' if old_cfg else 'stop', SERVICE],
                       capture_output=True, timeout=25, check=False)
        raise
    return status(entries)
